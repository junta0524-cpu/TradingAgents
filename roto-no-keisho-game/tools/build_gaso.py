def pixel_rule(px, block, py=None):
    py = py or px
    return ("%d×%dドットのドット絵を、1ドット=%dpxの正方形として%d×%dピクセルで描いてください。\n"
            "ドットの格子はきっちり揃え、1ドットの中で色が変わらないようにすること。\n\n"
            + STYLE_CORE + "\n\n"
            "【背景】透過ではなく、純粋なマゼンタ #FF00FF のベタ塗り。\n"
            "この色は被写体のどこにも使わないこと(あとで切り抜くための目印です)。"
            ) % (px, py, block, px * block, py * block)

